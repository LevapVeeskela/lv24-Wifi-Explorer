String? standardIeName(int id) => standardIeNames[id];

String? extensionIeName(int extId) => extensionIeNames[extId];

/// Tree title: `RSN (48)` or `HE Capabilities (255/35)`.
String ieTreeTitle(int id, int? extId) {
  if (id == 255 && extId != null) {
    final extName = extensionIeName(extId);
    return extName != null
        ? '$extName (255/$extId)'
        : 'Extension (255/$extId)';
  }
  final name = standardIeName(id);
  return name != null ? '$name ($id)' : 'Element ($id)';
}
